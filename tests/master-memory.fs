\ Run from a disposable flash page, with all test words in fixed RAM.
VARIABLE CHECKS VARIABLE FAILURES VARIABLE DONE
VARIABLE SAVED-DP VARIABLE SAVED-LATEST
VARIABLE ACTUAL VARIABLE EXPECTED
CREATE ERRORS 512 ALLOT
0 CHECKS ! 0 FAILURES ! 0 DONE !
: ASSERT
  1 CHECKS +! 0= IF
    FAILURES @ 80 < IF
      ERRORS FAILURES @ 6 * + DUP >R CHECKS @ SWAP !
      ACTUAL @ R@ 2 + ! EXPECTED @ R> 4 + !
    THEN 1 FAILURES +!
  THEN ;
: CHECK= DUP EXPECTED ! OVER ACTUAL ! = ASSERT ;
: RESTORE SAVED-DP @ DP ! SAVED-LATEST @ LATEST ! 0 STATE ! ;
: SAME HERE SAVED-DP @ CHECK= LATEST @ SAVED-LATEST @ CHECK= ;
: TRY-EVAL ['] EVALUATE CATCH DUP IF >R 2DROP R> THEN ;
: BYTE 90 C, ;
: CELL 4660 , ;
: GROW 1 ALLOT ;
: SHRINK -1 ALLOT ;
: HUGE -32768 ALLOT ;
: NOOP 0 ALLOT ;
: HUGE-ROOM 65535 ROOM ;
: MAKE-CREATE S" CREATE ZZ" TRY-EVAL ;
: MAKE-VARIABLE S" VARIABLE ZZ" TRY-EVAL ;
: MAKE-CONSTANT S" 7 CONSTANT ZZ" TRY-EVAL ;
: MAKE-VALUE S" 7 VALUE ZZ" TRY-EVAL ;

\ The quote at offset 5 is outside a source limited to five bytes.
HERE 83 C, 34 C, 32 C, 88 C, 89 C, 34 C, CONSTANT QUOTED
HERE 83 C, 34 C, 32 C, 34 C, CONSTANT EMPTY-QUOTED
: QUOTE-RESULT QUOTED 6 TRY-EVAL DUP 0= IF DROP 2DROP 0 THEN ;
: COMPILE-QUOTE
  SOURCE 2>R >IN @ >R STATE @ >R
  QUOTED 6 SOURCE! 3 >IN ! 1 STATE !
  ['] S" CATCH
  R> STATE ! R> 2R> SOURCE! >IN ! ;
: NAMES
