\ Dictionary bounds and distinct fixed RAM above C000, on a disposable ROM.
VARIABLE MEM-CHECKS VARIABLE MEM-FAILURES VARIABLE MEM-DONE
VARIABLE MEM-DP VARIABLE MEM-LATEST
0 MEM-CHECKS ! 0 MEM-FAILURES ! 0 MEM-DONE !
: MEM-ASSERT 1 MEM-CHECKS +! 0= IF 1 MEM-FAILURES +! THEN ;
: MEM-= = MEM-ASSERT ;
: MEM-GROW 1 ALLOT ;
: MEM-SHRINK 0 1 - ALLOT ;
: MEM-HUGE 32768 ALLOT ;
: MEM-NOOP 0 ALLOT ;
: MEM-CELL 4660 , ;
: MEM-BYTE 90 C, ;
: MEM-ROOM 65535 ROOM ;
: MEM-CREATE S" CREATE ZZ" DROP EVALUATE0 ;
: MEM-CREATE-MISSING S" CREATE" DROP EVALUATE0 ;
: MEM-COLON-MISSING S" :" DROP EVALUATE0 ;
: MEM-RESTORE MEM-LATEST @ LATEST ! MEM-DP @ DP ! ;
: MEM-SAME-LATEST LATEST @ MEM-LATEST @ MEM-= ;

\ Byte-built sources deliberately contain an early EOF before a closing quote.
HERE 83 C, 34 C, 32 C, 88 C, 34 C, 0 C, CONSTANT MEM-STRING-SOURCE
