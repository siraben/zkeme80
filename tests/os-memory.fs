: MEM-BAD-QUOTE
  MEM-BAD-STRING EVALUATE0 DUP 0= IF DROP 2DROP 0 THEN ;
: MEM-COMPILE-STRING
  INPUT-PTR @ >R STATE @ >R
  MEM-STRING-SOURCE 3 + INPUT-PTR ! 1 STATE !
  ['] S" CATCH R> STATE ! R> INPUT-PTR ! ;
: MEM-PARSE-CHECKS
  MEM-BAD-QUOTE 18 MEM-=
  MEM-BAD-DOT EVALUATE0 18 MEM-=
  MEM-BAD-COMPILED EVALUATE0 18 MEM-=
  MEM-RESTORE
  77 HERE C! 77 HERE 1+ C!
  MEM-STRING-SOURCE EVALUATE0 0 MEM-=
  1 MEM-= DUP HERE MEM-= DUP C@ 88 MEM-= 1+ C@ 0 MEM-=
  MEM-EMPTY-SOURCE EVALUATE0 0 MEM-=
  0 MEM-= C@ 0 MEM-=
  HERE MEM-DP @ MEM-=
  DP-LIMIT C@ >R DP-LIMIT 1+ C@ >R
  165 DP-LIMIT C! 90 DP-LIMIT 1+ C!
  DP-LIMIT DP ! MEM-STRING 8 MEM-=
  HERE DP-LIMIT MEM-= DP-LIMIT C@ 165 MEM-=
  DP-LIMIT 1+ C@ 90 MEM-=
  R> DP-LIMIT 1+ C! R> DP-LIMIT C!
  DP-LIMIT 5 - DP ! 77 HERE C!
  MEM-COMPILE-STRING 8 MEM-=
  HERE DP-LIMIT 5 - MEM-= HERE C@ 77 MEM-= MEM-SAME-LATEST
  DP-LIMIT 6 - DP ! MEM-COMPILE-STRING 0 MEM-=
  HERE DP-LIMIT MEM-= DP-LIMIT 2 - C@ 88 MEM-=
  DP-LIMIT 1- C@ 0 MEM-= MEM-SAME-LATEST
  MEM-RESTORE
;


