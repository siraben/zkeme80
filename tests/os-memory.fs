  \ Probe equal offsets in the two fixed RAM windows, away from test code.
  \ Restore both bytes before calling any resident or assertion words.
  40704 C@ >R 57088 C@ >R
  165 40704 C! 90 57088 C!
  40704 C@ 57088 C@
  R> 57088 C! R> 40704 C!
  90 MEM-= 165 MEM-=

