HERE 83 C, 34 C, 32 C, 65 C, 0 C, 66 C, 34 C, 0 C, CONSTANT MEM-BAD-STRING
HERE 46 C, 34 C, 32 C, 65 C, 0 C, 66 C, 34 C, 0 C, CONSTANT MEM-BAD-DOT
HERE 58 C, 32 C, 77 C, 69 C, 77 C, 45 C, 80 C, 65 C, 82 C, 84 C, 32 C, 83 C, 34 C, 32 C, 65 C, 0 C, 66 C, 34 C, 32 C, 59 C, 0 C, CONSTANT MEM-BAD-COMPILED

: MEM-STRING
